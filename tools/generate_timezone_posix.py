#!/usr/bin/env python3
"""Generate ESP-IDF POSIX TZ rules from IANA TZif footers."""

from __future__ import annotations

import argparse
import re
import struct
from pathlib import Path


def block_end(data: bytes, header: int, width: int) -> int:
    if data[header : header + 4] != b"TZif":
        raise ValueError("invalid TZif header")
    gmt_count, std_count, leap_count, time_count, type_count, char_count = struct.unpack(
        ">6I", data[header + 20 : header + 44]
    )
    size = (
        time_count * width
        + time_count
        + type_count * 6
        + char_count
        + leap_count * (width + 4)
        + std_count
        + gmt_count
    )
    end = header + 44 + size
    if end > len(data):
        raise ValueError("truncated TZif block")
    return end


def posix_footer(data: bytes) -> str | None:
    version = data[4:5]
    if version not in (b"2", b"3", b"4"):
        return None
    second_header = block_end(data, 0, 4)
    footer_start = block_end(data, second_header, 8)
    footer = data[footer_start:]
    if len(footer) < 3 or footer[0:1] != b"\n" or footer[-1:] != b"\n":
        return None
    text = footer[1:-1].decode("ascii", errors="strict")
    return text or None


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--zoneinfo", type=Path, required=True, help="IANA tzdata zoneinfo directory")
    parser.add_argument("--iana-version", required=True, help="IANA version label, such as 2026f")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    entries: list[tuple[str, str]] = []
    skipped: list[str] = []
    name_pattern = re.compile(r"^[A-Za-z0-9_+./-]+$")
    for path in sorted(args.zoneinfo.rglob("*")):
        if not path.is_file():
            continue
        name = path.relative_to(args.zoneinfo).as_posix()
        if name.split("/", 1)[0] in {"posix", "right"}:
            continue
        raw = path.read_bytes()
        if not raw.startswith(b"TZif"):
            continue
        try:
            footer = posix_footer(raw)
        except (ValueError, UnicodeDecodeError, struct.error):
            footer = None
        if not footer or not name_pattern.fullmatch(name):
            skipped.append(name)
            continue
        if any(char in footer for char in '\\"\r\n'):
            skipped.append(name)
            continue
        entries.append((name, footer))

    if not any(name == "America/Vancouver" for name, _ in entries):
        raise SystemExit("IANA database is missing America/Vancouver")
    if not entries:
        raise SystemExit("No TZif POSIX footers found")

    lines = [
        "/*",
        f" * IANA tzdata {args.iana_version}; POSIX TZ footer strings.",
        " * Generated by tools/generate_timezone_posix.py; do not edit by hand.",
        " * ESP-IDF applies these rules with setenv(\"TZ\", rule, 1) and tzset().",
        " */",
        "typedef struct { const char *iana; const char *posix; } timezone_posix_entry_t;",
        "static const timezone_posix_entry_t s_timezone_posix[] = {",
    ]
    lines.extend(f'    {{"{name}", "{rule}"}},' for name, rule in entries)
    lines.extend(("};", ""))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"IANA tzdata {args.iana_version}: {len(entries)} zones, {len(skipped)} files without POSIX footer")


if __name__ == "__main__":
    main()
